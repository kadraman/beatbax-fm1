/*
 * Host CLI: compile a `.bax` into a C header carrying the feature 004 compiled
 * song blob (baked at the device rate). Usage:
 *   embed-bax <song.bax> [sample_rate] [out.h]
 * Defaults: sample_rate = 44118, output = stdout.
 */

#include "gb_embed.h"
#include "gb_stream.h"
#include "song_parse.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void emit_inst(FILE *f, const gb_song_inst_t *inst) {
    fprintf(f, "    { .voice = %u, .duty_x10 = %uu, .env_initial = %u, .env_period = %u, .env_dir = %u,\n",
            inst->voice, inst->duty_x10, inst->env_initial, inst->env_period, inst->env_dir);
    fprintf(f, "      .sweep_present = %u, .sweep_time = %u, .sweep_dir = %u, .sweep_shift = %u,\n",
            inst->sweep_present, inst->sweep_time, inst->sweep_dir, inst->sweep_shift);
    fprintf(f, "      .wave_table = {");
    for (int i = 0; i < 32; i++) {
        fprintf(f, "%s%u", i ? "," : "", inst->wave_table[i]);
    }
    fprintf(f, "}, .wave_sum = %d, .wave_volume = %u,\n", inst->wave_sum, inst->wave_volume);
    fprintf(f, "      .noise_width = %u, .noise_note_index = %d, .noise_shift = %u, .noise_divisor = %u,\n",
            inst->noise_width, inst->noise_note_index, inst->noise_shift, inst->noise_divisor);
    if (inst->prog.enabled) {
        fprintf(f, "      .prog = { .rows = {");
        for (int i = 0; i < inst->prog.count; i++) {
            fprintf(f, "%s{%d,%d,%d}", i ? "," : "",
                    inst->prog.rows[i].offset, inst->prog.rows[i].vol, inst->prog.rows[i].duty);
        }
        fprintf(f, "}, .count = %d, .loop_to = %d, .enabled = 1 } },\n",
                inst->prog.count, inst->prog.loop_to);
    } else {
        fprintf(f, "      .prog = { .enabled = 0 } },\n");
    }
}

static void emit_fx(FILE *f, const gb_song_fx_t *fx) {
    fprintf(f, "    { .vib_depth = %d, .vib_rate = %d, .vib_waveform = %u, .vib_duration_ms = %d, .vib_delay_ms = %d,\n",
            fx->vib_depth, fx->vib_rate, (unsigned)fx->vib_waveform, fx->vib_duration_ms, fx->vib_delay_ms);
    fprintf(f, "      .arp_semis = {%d,%d,%d,%d}, .arp_count = %d,\n",
            fx->arp_semis[0], fx->arp_semis[1], fx->arp_semis[2], fx->arp_semis[3], fx->arp_count);
    fprintf(f, "      .port_speed = %d, .bend_semi_q16 = %d, .bend_delay_ms = %d, .bend_time_ms = %d, .bend_curve = \"%s\" },\n",
            fx->port_speed, (int)fx->bend_semi_q16, fx->bend_delay_ms, fx->bend_time_ms, fx->bend_curve);
}

static void emit_escaped(FILE *f, const char *s) {
    for (const char *p = s; *p; p++) {
        unsigned char c = (unsigned char)*p;
        if (c == '"' || c == '\\') {
            fputc('\\', f);
        }
        fputc(c, f);
    }
}

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: %s <song.bax> [sample_rate] [out.h]\n", argv[0]);
        return 2;
    }
    const char *path = argv[1];
    uint32_t rate = GB_RENDER_DEVICE_RATE;
    if (argc >= 3) {
        rate = (uint32_t)strtoul(argv[2], NULL, 10);
    }

    bax_song_t song;
    bax_error_t err;
    if (!bax_song_parse_file(path, &song, &err)) {
        fprintf(stderr, "parse failed: [%d:%d] (%s) %s\n", err.line, err.column, err.construct, err.message);
        return 1;
    }

    gb_song_blob_t blob;
    char errbuf[256];
    if (!gb_blob_build(&song, rate, &blob, errbuf, sizeof(errbuf))) {
        fprintf(stderr, "blob build failed: %s\n", errbuf);
        bax_song_free(&song);
        return 1;
    }

    FILE *f = stdout;
    if (argc >= 4) {
        f = fopen(argv[3], "w");
        if (!f) {
            fprintf(stderr, "cannot open %s\n", argv[3]);
            return 1;
        }
    }

    fprintf(f, "/* Auto-generated by tools/embed-bax.c from %s. DO NOT EDIT. */\n", path);
    fprintf(f, "#ifndef BAX_GB_SONG_EMBED_H\n#define BAX_GB_SONG_EMBED_H\n");
    fprintf(f, "#include \"gb_stream.h\"\n\n");

    if (blob.inst_count > 0) {
        fprintf(f, "static const gb_song_inst_t bax_insts[%u] = {\n", blob.inst_count);
        for (uint16_t i = 0; i < blob.inst_count; i++) {
            emit_inst(f, &blob.insts[i]);
        }
        fprintf(f, "};\n\n");
    }
    if (blob.fx_count > 0) {
        fprintf(f, "static const gb_song_fx_t bax_fxs[%u] = {\n", blob.fx_count);
        for (uint16_t i = 0; i < blob.fx_count; i++) {
            emit_fx(f, &blob.fxs[i]);
        }
        fprintf(f, "};\n\n");
    }
    fprintf(f, "static const gb_song_event_t bax_events[%u] = {\n", blob.event_count);
    for (uint32_t i = 0; i < blob.event_count; i++) {
        const gb_song_event_t *e = &blob.events[i];
        fprintf(f, "    { %uu, %uu, %d, %u, %u, %u, %u, %u, %d },\n",
                e->start, e->len, (int)e->midi, e->inst, e->fx, e->channel,
                e->join, e->hold, (int)e->vol_override);
    }
    fprintf(f, "};\n\n");

    fprintf(f, "static const char bax_name[] = \"");
    emit_escaped(f, blob.name);
    fprintf(f, "\";\n\n");

    fprintf(f, "static const gb_song_blob_t gb_song_blob = {\n");
    fprintf(f, "    .magic = 0x%08Xu, .version = %uu, .sample_rate = %uu, .total_frames = %uu,\n",
            blob.magic, blob.version, blob.sample_rate, blob.total_frames);
    fprintf(f, "    .scale = %uu, .bpm = %uu, .name = bax_name,\n", blob.scale, blob.bpm);
    fprintf(f, "    .insts = %s, .inst_count = %u, .fxs = %s, .fx_count = %u,\n",
            blob.inst_count ? "bax_insts" : "0", blob.inst_count,
            blob.fx_count ? "bax_fxs" : "0", blob.fx_count);
    fprintf(f, "    .events = bax_events, .event_count = %uu,\n", blob.event_count);
    fprintf(f, "};\n\n");
    fprintf(f, "#endif /* BAX_GB_SONG_EMBED_H */\n");

    if (f != stdout) {
        fclose(f);
    }
    gb_blob_free(&blob);
    bax_song_free(&song);
    return 0;
}
